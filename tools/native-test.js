import Clutter from 'gi://Clutter';
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import St from 'gi://St';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';
const delay=ms=>new Promise(r=>GLib.timeout_add_once(GLib.PRIORITY_DEFAULT,ms,r));
const assert=(v,m)=>{if(!v)throw Error(m);};
export async function run(setup,aod){
 const launcher=new Gio.SubprocessLauncher({flags:Gio.SubprocessFlags.NONE});
 launcher.setenv('WAYLAND_DISPLAY',setup.root+'/runtime/wayland-0',true);
 launcher.setenv('GDK_BACKEND','wayland',true);
 const app=launcher.spawnv([GLib.getenv('AOD_GJS'),'-m',setup.dir.get_child('test-window.js').get_path()]);
 let popup;
 let beat=0,last=GLib.get_monotonic_time();const timer=GLib.timeout_add(GLib.PRIORITY_DEFAULT,16,()=>{const now=GLib.get_monotonic_time();beat=Math.max(beat,(now-last)/1000);last=now;return GLib.SOURCE_CONTINUE;});
 try{
  aod.wake();aod._settings.set_string('mode','live');aod._settings.set_boolean('automatic',true);
  aod._settings.set_boolean('grayscale',false);aod._settings.set_uint('idle-seconds',300);
  Main.overview.hide();let source;
  assert(!Main.panel.statusArea[aod.uuid],'standalone AOD panel icon still exists');
  const tile=aod._toggle;
  assert(tile.get_parent()&&tile.checked,'Quick Settings tile missing or off by default');
  tile.checked=false;await delay(50);
  assert(!aod._settings.get_boolean('automatic')&&!aod._idleWatch,'tile did not disable idle activation');
  tile.checked=true;await delay(50);
  assert(aod._settings.get_boolean('automatic')&&aod._idleWatch,'tile did not restore idle activation');
  Main.panel.statusArea.quickSettings.menu.open();await delay(80);await setup.capture('quick-settings.png');
  tile.menu.open();await delay(300);await setup.capture('quick-settings-menu.png');
  tile.menu.close();Main.panel.statusArea.quickSettings.menu.close();
  const initialModalCount=Main.modalCount;
  for(let i=0;i<60;i++){source=global.get_window_actors().find(a=>a.meta_window.get_title()==='AOD native window');if(source)break;await delay(50);}
  assert(source,'native GTK fixture did not map');await delay(180);await setup.capture('before.png');
  aod._interfaceSettings.set_string('color-scheme','prefer-light');
  const start=GLib.get_monotonic_time();
  tile.menu._getMenuItems().find(item=>item.label?.text==='Preview').activate(null);await delay(80);
  assert(!Main.panel.statusArea.quickSettings.menu.isOpen,'Preview left Quick Settings open');
  assert(aod.active&&aod._clones.has(source),'native window not cloned');
  assert(aod._interfaceSettings.get_string('color-scheme')==='prefer-dark','dark mode not requested');
  assert(GLib.get_monotonic_time()-start<400000,'AOD feedback exceeded400ms');
  const entry=aod._clones.get(source);assert(entry.frame.width>0&&entry.clone.width>0,'missing geometry');
  const initialRect=source.meta_window.get_frame_rect();
  const clip=entry.clone.get_clip();assert(Math.abs(clip[2]-initialRect.width)<2&&Math.abs(clip[3]-initialRect.height)<2,'filter includes shadow outside frame');
  await setup.capture('aod.png');await delay(1100);await setup.capture('progress.png');
  launcher.setenv('AOD_TEST_WINDOW_TITLE','Background popup',true);
  popup=launcher.spawnv([GLib.getenv('AOD_GJS'),'-m',setup.dir.get_child('test-window.js').get_path()]);
  let popupActor;
  for(let i=0;i<60;i++){popupActor=global.get_window_actors().find(a=>a.meta_window.get_title()==='Background popup');if(popupActor)break;await delay(50);}
  await delay(250);assert(popupActor&&aod.active,'new window/focus dismissed AOD');
  const synthetic={type:()=>Clutter.EventType.MOTION,get_flags:()=>Clutter.EventFlags.FLAG_SYNTHETIC};
  aod._onCapturedEvent(synthetic);assert(aod.active,'synthetic pointer motion dismissed AOD');
  const shellPopup=new St.Widget({width:200,height:100,style:'background:white;'});
  Main.uiGroup.add_child(shellPopup);assert(Main.uiGroup.get_last_child()===aod._overlay,'Shell popup covered AOD');
  Main.uiGroup.set_child_above_sibling(shellPopup,null);await delay(80);
  assert(Main.uiGroup.get_last_child()===aod._overlay,'restacked Shell popup covered AOD');shellPopup.destroy();
  popup.force_exit();popup=null;await delay(200);

  aod._settings.set_boolean('grayscale',true);aod.enter();await delay(100);await setup.capture('grayscale.png');
  aod._settings.set_boolean('grayscale',false);aod.enter();await delay(100);
  const keyboard=global.stage.context.get_backend().get_default_seat().create_virtual_device(Clutter.InputDeviceType.KEYBOARD_DEVICE);
  keyboard.notify_keyval(GLib.get_monotonic_time(),Clutter.KEY_a,Clutter.KeyState.PRESSED);
  keyboard.notify_keyval(GLib.get_monotonic_time(),Clutter.KEY_a,Clutter.KeyState.RELEASED);await delay(80);
  assert(!aod.active&&!aod._clones.size&&!aod._cursorHidden,'keyboard wake/cleanup');
  assert(aod._interfaceSettings.get_string('color-scheme')==='prefer-light','light preference not restored');
  aod.enter();await delay(80);const pointer=global.stage.context.get_backend().get_default_seat().create_virtual_device(Clutter.InputDeviceType.POINTER_DEVICE);
  pointer.notify_absolute_motion(GLib.get_monotonic_time(),30,60);await delay(80);assert(!aod.active,'pointer wake');
  aod.enter();await delay(80);pointer.notify_button(GLib.get_monotonic_time(),Clutter.BUTTON_PRIMARY,Clutter.ButtonState.PRESSED);
  pointer.notify_button(GLib.get_monotonic_time(),Clutter.BUTTON_PRIMARY,Clutter.ButtonState.RELEASED);await delay(80);assert(!aod.active,'mouse button wake');
  aod.enter();await delay(80);pointer.notify_discrete_scroll(GLib.get_monotonic_time(),Clutter.ScrollDirection.DOWN,Clutter.ScrollSource.WHEEL);
  await delay(80);assert(!aod.active,'scroll wake');
  aod.enter();await delay(50);source.meta_window.move_resize_frame(false,300,180,700,430);await delay(180);
  const rect=source.meta_window.get_frame_rect();assert(Math.abs(aod._clones.get(source).frame.width-rect.width)<2,'frame did not follow resize');
  aod.wake();await setup.capture('restored.png');
  const oldIdle=aod._idle;let inhibited=true,beforeReply=null;
  const service=Gio.DBusExportedObject.wrapJSObject('<node><interface name="org.gnome.SessionManager"><method name="IsInhibited"><arg direction="in" type="u"/><arg direction="out" type="b"/></method><signal name="InhibitorAdded"><arg type="o"/></signal><signal name="InhibitorRemoved"><arg type="o"/></signal></interface></node>',{IsInhibited:()=>{const before=beforeReply;beforeReply=null;before?.();return inhibited;}});
  service.export(Gio.DBus.session,'/org/gnome/SessionManager');
  const owner=Gio.bus_own_name_on_connection(Gio.DBus.session,'org.gnome.SessionManager',Gio.BusNameOwnerFlags.NONE,null,null);
  try{
   aod._idle={get_idletime:()=>301000,add_user_active_watch:fn=>oldIdle.add_user_active_watch(fn),remove_watch:id=>oldIdle.remove_watch(id)};
   await delay(80);aod._tryIdle();await delay(100);assert(!aod.active,'idle inhibitor ignored');
   inhibited=false;beforeReply=()=>source.meta_window.make_fullscreen();
   aod._tryIdle();await delay(250);
   assert(source.meta_window.is_fullscreen()&&!aod.active,'fullscreen entered during inhibitor query did not block AOD');
   aod._tryIdle();await delay(150);assert(!aod.active,'fullscreen did not block idle activation');
   aod.enter();await delay(100);assert(aod.active,'manual fullscreen preview blocked');aod.wake();
   source.meta_window.unmake_fullscreen();await delay(250);
   assert(aod.active,'leaving fullscreen did not reconsider idle activation');
   source.meta_window.make_fullscreen();await delay(150);
   assert(aod.active,'fullscreen change dismissed active AOD');
   source.meta_window.unmake_fullscreen();await delay(150);aod.wake();
   inhibited=false;service.emit_signal('InhibitorRemoved',new GLib.Variant('(o)',['/test/inhibitor']));await delay(120);assert(aod.active,'idle did not activate after inhibitor removed');
   inhibited=true;service.emit_signal('InhibitorAdded',new GLib.Variant('(o)',['/test/inhibitor']));await delay(120);assert(aod.active,'new inhibitor dismissed active AOD');aod.wake();
   aod._idle=oldIdle;inhibited=false;
   aod._settings.set_uint('idle-seconds',10);
   pointer.notify_absolute_motion(GLib.get_monotonic_time(),55,85);await delay(100);
   aod._watchIdle();await delay(10800);
   assert(aod.active,'real native idle timeout did not activate AOD');
   aod.wake();aod._settings.set_uint('idle-seconds',300);

  }finally{aod.wake();aod._idle=oldIdle;service.unexport();Gio.bus_unown_name(owner);}
  const settingsProcess=new Gio.SubprocessLauncher({flags:Gio.SubprocessFlags.NONE});
  settingsProcess.setenv('GSETTINGS_SCHEMA_DIR',Main.extensionManager.lookup('aod@neg-zero.com').dir.get_child('schemas').get_path(),true);
  const preferences=settingsProcess.spawnv(['gsettings','set','org.gnome.shell.extensions.zenos-aod','mode','lockscreen']);
  await preferences.wait_check_async(null);await delay(150);
  assert(aod._settings.get_string('mode')==='lockscreen','preferences process did not reach Shell settings');
  aod._settings.set_boolean('grayscale',true);aod.enter();await delay(100);
  assert(aod.active&&aod._usingShield,'native lockscreen mode inactive');
  assert(Main.screenShield._dialog?._clock,'actual GNOME lockscreen clock not used');
  assert(!Main.screenShield.locked,'AOD unexpectedly authenticated/locked the session');
  assert(Main.screenShield._dialog._clock.constructor.name==='ModifiedClock','installed lockscreen extension did not customize native clock');
  Main.screenShield._dialog.emit('wake-up-screen');await delay(100);
  assert(aod.active&&Main.screenShield.active,'notification dismissed native AOD');
  aod._onCapturedEvent(synthetic);assert(aod.active,'synthetic input dismissed native AOD');
  await setup.capture('lockscreen.png');
  keyboard.notify_keyval(GLib.get_monotonic_time(),Clutter.KEY_a,Clutter.KeyState.PRESSED);
  keyboard.notify_keyval(GLib.get_monotonic_time(),Clutter.KEY_a,Clutter.KeyState.RELEASED);
  await delay(350);assert(!aod.active&&!Main.screenShield.locked,'lockscreen wake');
  assert(aod._interfaceSettings.get_string('color-scheme')==='prefer-light','lockscreen theme restore');
  aod.enter();await delay(100);pointer.notify_absolute_motion(GLib.get_monotonic_time(),75,95);await delay(350);
  assert(!aod.active&&!Main.screenShield.locked,'native lockscreen pointer wake');
  aod.enter();await delay(100);pointer.notify_button(GLib.get_monotonic_time(),Clutter.BUTTON_PRIMARY,Clutter.ButtonState.PRESSED);
  pointer.notify_button(GLib.get_monotonic_time(),Clutter.BUTTON_PRIMARY,Clutter.ButtonState.RELEASED);await delay(350);
  assert(!aod.active&&!Main.screenShield.locked,'native lockscreen button wake');
  aod.enter();await delay(100);pointer.notify_discrete_scroll(GLib.get_monotonic_time(),Clutter.ScrollDirection.DOWN,Clutter.ScrollSource.WHEEL);
  await delay(350);assert(!aod.active&&!Main.screenShield.locked,'native lockscreen scroll wake');
  assert(Main.modalCount===initialModalCount,'AOD leaked an input grab');
  aod._settings.set_boolean('grayscale',false);aod._settings.set_string('mode','live');
  let removed=false;tile.connect('destroy',()=>{removed=true;});
  aod.disable();assert(removed,'tile survived extension disable');
  aod.enable();assert(aod._toggle!==tile&&aod._toggle.get_parent(),'tile failed to return after re-enable');
  assert(beat<400,'UI heartbeat exceeded400ms');
  setup.write('result.json',{pass:true,nativeWindow:true,liveUpdates:true,filledText:true,windowFrame:true,shadowClipped:true,themeRestore:true,nativeLockscreen:true,sharedPreferences:true,grayscaleBothModes:true,quickSettingsTile:true,frameRect:{x:initialRect.x,y:initialRect.y,width:initialRect.width,height:initialRect.height},keyboardWake:true,pointerWake:true,cleanup:true,idleInhibitors:true,fullscreenGuard:true,fullscreenReplyRace:true,fullscreenManualPreview:true,nativeIdleTimeout:true,hidOnlyWake:true,backgroundWindow:true,buttonWake:true,scrollWake:true,maxGap:beat});
 }finally{GLib.source_remove(timer);aod.wake();popup?.force_exit();app.force_exit();}
}
